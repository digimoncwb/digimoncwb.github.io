import fs from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const documents = JSON.parse(await fs.readFile(path.join(root, 'legal/documents.json'), 'utf8'));
const migrationFilename = documents.migration || '20261025180000_register_site_legal_documents.sql';
if (!/^\d{14}_[a-z0-9_]+\.sql$/.test(migrationFilename))
    throw Error('Nome de migração legal inválido.');
const escape = (value) =>
    String(value).replace(
        /[&<>"']/g,
        (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]
    );
const literal = (value) => {
    if (String(value).includes('$sitelegal$')) throw Error('Delimitador inválido.');
    return `$sitelegal$${value}$sitelegal$`;
};
const inserts = [];
const bundled = {};
for (const kind of ['terms', 'privacy']) {
    const document = documents[kind];
    const body = [
        document.title,
        `Versão ${documents.version} · ${documents.publishedDate}`,
        ...document.sections.flatMap((section) => [section.title, ...section.paragraphs])
    ].join('\n\n');
    const url = `https://digimoncwb.github.io/legal/${document.filename}`;
    bundled[kind] = {
        title: document.title,
        version: documents.version,
        url,
        sections: document.sections
    };
    const other = documents[kind === 'terms' ? 'privacy' : 'terms'];
    const content = document.sections
        .map(
            (section) =>
                `<section><h2>${escape(section.title)}</h2>${section.paragraphs.map((text) => `<p>${escape(text)}</p>`).join('\n')}</section>`
        )
        .join('\n');
    await fs.writeFile(
        path.join(root, 'legal', document.filename),
        `<!doctype html>
<html lang="pt-BR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="dark light"><title>${escape(document.title)} — DIGIMON CWB</title><link rel="stylesheet" href="legal.css"></head>
<body><main><nav aria-label="Navegação"><a href="../index.html">Voltar ao site</a><a href="${other.filename}">${escape(other.title)}</a></nav><header><p>DIGIMON CWB</p><h1>${escape(document.title)}</h1><p>Versão ${escape(documents.version)} · ${escape(documents.publishedDate)}</p></header>${content}<footer><a href="mailto:dulopes1997@gmail.com">Contas e privacidade: dulopes1997@gmail.com</a></footer></main></body></html>\n`
    );
    inserts.push(`insert into public.site_legal_documents(kind,version,url,body,sha256)
values('${kind}',${literal(documents.version)},${literal(url)},${literal(body)},encode(pg_catalog.sha256(convert_to(${literal(body)},'UTF8')),'hex'))
on conflict(kind,version) do nothing;
do $$ begin
    if not exists(select 1 from public.site_legal_documents where kind='${kind}' and version=${literal(documents.version)}
        and url=${literal(url)} and body=${literal(body)}) then
        raise exception 'A versão legal já existe com outro conteúdo. Publique uma nova versão.';
    end if;
end $$;`);
}
const migration = `begin;

-- Generated by scripts/prepare-site-legal.mjs from legal/documents.json.
-- Deploy the matching public HTML pages before applying this migration.
-- This registers documents without enabling general account enforcement.
${inserts.join('\n\n')}

update public.site_security_config set
    terms_url='https://digimoncwb.github.io/legal/${documents.terms.filename}',
    terms_version=${literal(documents.version)},
    privacy_url='https://digimoncwb.github.io/legal/${documents.privacy.filename}',
    privacy_version=${literal(documents.version)},updated_at=now() where singleton;

commit;
`;
await fs.writeFile(path.join(root, 'database/migrations', migrationFilename), migration);
await fs.writeFile(
    path.join(root, 'frontend/shell/legal-documents.generated.ts'),
    `// Generated by scripts/prepare-site-legal.mjs. Edit legal/documents.json.\nexport const siteLegalDocuments = ${JSON.stringify(bundled, null, 4)} as const;\n`
);
console.log('Páginas legais e migração geradas com o mesmo conteúdo e versão.');
