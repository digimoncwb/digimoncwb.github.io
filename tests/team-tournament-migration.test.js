const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');

const store = '00000000-0000-0000-0000-000000000001';
const player = (index) => `00000000-0000-0000-0000-${String(index + 10).padStart(12, '0')}`;
const deck = '00000000-0000-0000-0000-000000000002';
const event = {
    store_id: store,
    tournament_date: '2026-10-10',
    tournament_name: '2v2',
    total_players: 4,
    format_id: 1
};
const results = Array.from({ length: 4 }, (_, index) => ({
    player_id: player(index),
    deck_id: deck,
    match_points: index < 2 ? 9 : 6
}));

test('2v2 transaction supports save, edit, pairs, solo coexistence and rolls back invalid data', async () => {
    const db = new PGlite();
    try {
        await db.exec(`
            CREATE TABLE stores(id uuid PRIMARY KEY, name text);
            CREATE TABLE formats(id bigint PRIMARY KEY, code text, is_default boolean);
            CREATE TABLE players(id uuid PRIMARY KEY, name text);
            CREATE TABLE decks(id uuid PRIMARY KEY, name text);
            CREATE TABLE deck_images(id uuid PRIMARY KEY, deck_id uuid, image_url text, created_at timestamptz);
            CREATE TABLE tournament(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_id uuid,
                tournament_date date, tournament_name text, total_players smallint, format_id bigint,
                instagram_link text, rounds smallint);
            CREATE TABLE tournament_results(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
                tournament_id bigint REFERENCES tournament(id), store_id uuid NOT NULL, tournament_date date NOT NULL,
                total_players smallint, placement smallint, player_id uuid REFERENCES players(id),
                deck_id uuid REFERENCES decks(id), match_points integer, decklist text,
                CONSTRAINT unique_player_per_tournament UNIQUE(store_id,tournament_date,player_id),
                CONSTRAINT unique_tournament_placement UNIQUE(store_id,tournament_date,placement));
            CREATE TABLE tournament_ocr_files(tournament_id bigint, batch_id uuid, storage_path text,
                original_name text, mime_type text, size_bytes bigint);
            CREATE TABLE tournament_digilab_sync(tournament_id bigint PRIMARY KEY, digilab_tournament_id bigint, status text);
            CREATE FUNCTION digilab_normalize(text) RETURNS text LANGUAGE sql AS 'select lower($1)';
            INSERT INTO stores VALUES('${store}','Loja');
            INSERT INTO formats VALUES(1,'EX13',true);
            INSERT INTO decks VALUES('${deck}','Deck');
            INSERT INTO players VALUES ${Array.from({ length: 4 }, (_, i) => `('${player(i)}','Player ${i}')`).join(',')};
        `);
        const migration = readFileSync(
            'database/migrations/20261010000000_local_2v2_tournaments.sql',
            'utf8'
        );
        await db.exec(migration);
        const save = async (id, details, rows) =>
            (
                await db.query(
                    'select save_tournament_transaction($1,$2::jsonb,$3::jsonb) as saved',
                    [id, JSON.stringify(details), JSON.stringify(rows)]
                )
            ).rows[0].saved;
        const saved = await save(null, event, results);
        const id = saved.tournament_id;
        assert.equal(saved.results_count, 4);
        const read = async () =>
            (
                await db.query(
                    'select id,placement,team_member,player_id,match_points from tournament_results where tournament_id=$1 order by placement,team_member',
                    [id]
                )
            ).rows;
        const original = await read();
        assert.deepEqual(
            original.map((row) => [row.placement, row.team_member]),
            [
                [1, 1],
                [1, 2],
                [2, 1],
                [2, 2]
            ]
        );
        // Reorder existing members/teams without losing their result IDs/decklists.
        const swapped = [original[2], original[3], original[1], original[0]].map((row) => ({
            ...row,
            deck_id: deck
        }));
        await save(id, event, swapped);
        assert.deepEqual(
            (await read()).map((row) => row.id),
            swapped.map((row) => row.id)
        );
        const solo = await save(null, { ...event, tournament_name: 'Semanal', total_players: 1 }, [
            results[0]
        ]);
        assert.notEqual(solo.tournament_id, id);
        const before = await read();
        for (const [details, rows] of [
            [{ ...event, total_players: 3 }, results.slice(0, 3)],
            [event, [results[0], results[0], ...results.slice(2)]],
            [event, results.map((row, index) => (index === 0 ? { ...row, deck_id: null } : row))],
            [event, results.map((row, index) => (index === 0 ? { ...row, match_points: 0 } : row))]
        ]) {
            await assert.rejects(save(id, details, rows));
            assert.deepEqual(await read(), before, 'invalid saves must be atomic');
        }
        await assert.rejects(
            db.query("insert into tournament_digilab_sync values($1,123,'matched')", [id]),
            /exclusivamente local/
        );
        await assert.rejects(
            db.query('update tournament_results set deck_id=null where id=$1', [before[0].id]),
            /dois jogadores/
        );
        await assert.rejects(
            db.query('update tournament_results set tournament_id=null where id=$1', [
                before[0].id
            ]),
            /dois jogadores/
        );
        await assert.rejects(
            db.query("update tournament set tournament_name='Semanal' where id=$1", [id]),
            /Apenas torneios 2v2/
        );
        await assert.rejects(
            db.query(
                "select sync_digilab_tournament_atomic(123,$1::jsonb,$2::jsonb,'[]','[]',$3)",
                [
                    JSON.stringify({
                        player_count: 4,
                        date: event.tournament_date,
                        store: { name: 'Loja' }
                    }),
                    JSON.stringify(results),
                    id
                ]
            ),
            /exclusivamente local/
        );
        await save(id, { ...event, total_players: 2 }, swapped.slice(0, 2));
        assert.equal((await read()).length, 2);
        await db.exec(migration);
        assert.equal((await read()).length, 2, 'migration is safe to reapply');
    } finally {
        await db.close();
    }
});
